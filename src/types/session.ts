import type { CookieJar } from 'tough-cookie';

/**
 * Encapsulates the internal state of an active Plumware session proxy lifecycle.
 * Maintained in transient cache keyed by unique `sessionToken`.
 */
export interface SessionState {
  /** Cryptographically random unique identifier for this proxy session */
  sessionToken: string;

  /** Isolated tough-cookie CookieJar retaining upstream PHPSESSID and related cookies */
  cookieJar: CookieJar;

  /** Hidden form token extracted from Plumware form (f) */
  f?: string;

  /** Hidden encrypted financial year token extracted from Plumware form (enc_fy) */
  encFy?: string;

  /** Target academic financial year (e.g. '2026-27') */
  fy: string;

  /** Organization name expected by Plumware backend (comp) */
  comp?: string;

  /** Static routing token required in form POST (t='swx') */
  t?: string;

  /** Dynamic random number nonce generated by Plumware (HRAND_NUM) */
  hrandNum?: string;

  /** Relative path to the CAPTCHA image (e.g. 'images/captcha/captcha_12345.jpg') */
  captchaPath?: string;

  /** Epoch millisecond timestamp when session was initialized */
  createdAt: number;

  /** Epoch millisecond timestamp after which session is permanently invalidated */
  expiresAt: number;

  /** Whether the session has completed successful credential verification */
  isAuthenticated: boolean;

  /** Roll number associated with the session once authenticated */
  rollNo?: string;

  /** Serialized cookie string for authenticated API calls */
  serializedCookies?: string;
}
